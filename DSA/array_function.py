#array function using linspace
from numpy import *
a=linspace(1,5,5)
print(a)

#array function using logspace
from numpy import *
a=logspace(1,5,4)
print(a)

#array function using arange
from numpy import *
a=arange(1,10,3)
print("arange(1,10,4) : ",a)
b=arange(10)
print("arange(10) : ",b)
c=arange(4,10)
print("arange(4,10) : ",c)

#array function using zeros and ones
from numpy import *
a=zeros(5)
print("zeros : ",a)
b=ones(8)
print("ones : ",b)

